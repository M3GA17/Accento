"""Generate Rust and UI metadata from the checked-in, source-attributed language registry."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
languages = json.loads((root/'localization/languages.json').read_text(encoding='utf8'))
characters = json.loads((root/'localization/characters.json').read_text(encoding='utf8'))
currencies = json.loads((root/'localization/currencies.json').read_text(encoding='utf8'))
def char(value):
    return "'" + {'\0':'\\0',"'":"\\'",'\\':'\\\\'}.get(value,value) + "'"
lines = ['// Generated by scripts/generate-language-catalog.py; edit localization data instead.',
         '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub enum Language {']
lines.extend('    '+item['variant']+',' for item in languages)
lines += ['}', 'impl Language {', '    pub const ALL: &\'static [Self] = &[']
lines.extend('        Self::'+item['variant']+',' for item in languages)
lines += ['    ];', '    pub fn code(self) -> &\'static str { match self {']
lines.extend(f'        Self::{item["variant"]} => "{item["code"]}",' for item in languages)
lines += ['    }}','    pub fn from_code(code: &str) -> Option<Self> { match code {']
lines.extend(f'        "{item["code"]}" => Some(Self::{item["variant"]}),' for item in languages)
lines += ['        _ => None,','    }}','}', "pub type CharacterMapping = (char, &'static str, &'static str);", "pub type LanguageMapping = (&'static str, &'static [CharacterMapping]);", 'pub const CHARACTER_MAPS: &[LanguageMapping] = &[']
for item in languages:
    triples = []
    for base,pairs in characters[item['code']]['maps'].items():
        triples.extend('('+char(base)+', '+json.dumps(lower,ensure_ascii=False)+', '+json.dumps(upper,ensure_ascii=False)+')' for lower,upper in pairs)
    lines.append('    ("'+item['code']+'", &['+', '.join(triples)+']),')
lines += ['];','']
lines.append("pub const CURRENCY_MAPS: &[(char, &[&str])] = &[")
for base, symbols in currencies.items():
    assert len(base) == 1 and 'a' <= base <= 'z', base
    assert symbols and all(isinstance(symbol, str) and symbol for symbol in symbols), base
    assert len(symbols) == len(set(symbols)), base
    lines.append('    ('+char(base)+', &['+', '.join(json.dumps(symbol, ensure_ascii=False) for symbol in symbols)+']),')
lines += ['];', '']
(root/'crates/accento-core/src/catalog_generated.rs').write_text('\n'.join(lines),encoding='utf8')
codes = ', '.join(json.dumps(item['code']) for item in languages)
(root/'crates/accento-platform/src/i18n_locales.rs').write_text('// Generated from localization/languages.json.\npub const UI_CODES: [&str; '+str(len(languages))+'] = ['+codes+'];\n',encoding='utf8')
print(f'{len(languages)} shared language definitions generated.')
